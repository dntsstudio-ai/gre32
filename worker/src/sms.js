// ============================================================
//  worker/src/sms.js — Извлечение суммы платежа из текста SMS
//  банка о зачислении по СБП.
//
//  Не привязываемся к точной формулировке банка (она может немного
//  отличаться/меняться) — просто находим ВСЕ числа вида "85.43р" /
//  "85,43 руб" / "85.43 RUB" в тексте и возвращаем их по порядку.
//  Дальше (см. index.js) каждое число проверяется на совпадение с
//  ожидающим заказом — совпадёт именно переведённая сумма, а не,
//  например, остаток баланса, даже если он тоже попал в список.
// ============================================================
export function extractAmountCandidates(text) {
    if (!text) return [];
    // Без \b: JS-регексы считают "словом" только [A-Za-z0-9_], кириллица
    // в эту категорию не входит, поэтому границы слов с ней не работают.
    const re = /(\d{1,7}[.,]\d{2})\s*(?:₽|руб\.?|р\.?|rub)(?![a-zа-яё])/gi;
    const out = [];
    let m;
    while ((m = re.exec(text)) !== null) {
        const num = parseFloat(m[1].replace(',', '.'));
        if (!Number.isNaN(num)) out.push(num);
    }
    return out;
}
